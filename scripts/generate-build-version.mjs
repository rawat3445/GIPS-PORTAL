import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const outputFile = path.join(
  projectRoot,
  "src",
  "app",
  "lib",
  "buildVersion.js",
);

function run(command) {
  try {
    return execSync(command, {
      cwd: projectRoot,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
  } catch {
    return "";
  }
}

const insideGitRepository = run("git rev-parse --is-inside-work-tree") === "true";
const isShallowRepository =
  run("git rev-parse --is-shallow-repository") === "true";

if (insideGitRepository && isShallowRepository) {
  try {
    execSync("git fetch --unshallow --tags", {
      cwd: projectRoot,
      stdio: "ignore",
    });
  } catch {
    // Vercel uses a shallow clone by default. If unshallow fails,
    // we still fall back to whatever history is available.
  }
}

const commitCount = Number.parseInt(run("git rev-list --count HEAD"), 10);
const normalizedCommitCount =
  Number.isFinite(commitCount) && commitCount > 0 ? commitCount : 1;
const commitSha = run("git rev-parse --short HEAD");
const generatedAt = new Date().toISOString();

const fileContents = `// Auto-generated by scripts/generate-build-version.mjs
export const buildVersion = "${normalizedCommitCount}";
export const buildCommitSha = "${commitSha || ""}";
export const buildGeneratedAt = "${generatedAt}";
`;

mkdirSync(path.dirname(outputFile), { recursive: true });
writeFileSync(outputFile, fileContents, "utf8");

console.log(`Generated build version ${normalizedCommitCount}`);
